import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const dependency = process.env.CHROME_LUCIDE_DIR || path.dirname(require.resolve('lucide-static/package.json'));
const names = ['menu', 'x', 'sun', 'moon', 'monitor', 'mail'];
const icons = {};
for (const name of names) {
  const source = await fs.readFile(path.join(dependency, 'icons', `${name}.svg`), 'utf8');
  icons[name] = source.replace(/<!--[\s\S]*?-->/g, '').trim()
    .replace('<svg', '<svg aria-hidden="true" focusable="false"').replace(/\s+/g, ' ');
}
const brandFiles = {
  BRAND_LOGO_DATA_URL: 'logo-hr.svg',
  BRAND_LOGO_LIGHT_DATA_URL: 'logo-hr-light.svg',
  BRAND_LOGO_DARK_DATA_URL: 'logo-hr-dark.svg',
  BRAND_FAVICON_DATA_URL: 'favicon.svg',
};
let generated = '// Generated by scripts/generate-assets.mjs from Lucide 1.66.0 (ISC) and assets/*.svg. Do not edit.\n'
  + `export const icons = ${JSON.stringify(icons, null, 2)};\n`;
for (const [name, filename] of Object.entries(brandFiles)) {
  const svg = await fs.readFile(path.join(root, 'assets', filename), 'utf8');
  // Descriptive source comments and whitespace need not be repeated in each SSR header.
  const compact = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/>\s+</g, '><').trim();
  generated += `export const ${name} = ${JSON.stringify(`data:image/svg+xml,${encodeURIComponent(compact)}`)};\n`;
}
const target = path.join(root, 'src/assets.generated.mjs');
if (process.argv.includes('--check')) {
  if (await fs.readFile(target, 'utf8') !== generated) throw new Error('Shared chrome assets drifted; run pnpm --filter @herong/site-chrome generate:assets');
  console.log('Shared chrome assets match the canonical SVG and installed Lucide package.');
} else {
  await fs.writeFile(target, generated);
  console.log('Generated shared chrome icons and HR brand data URL.');
}
