import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
// Reuse the workspace's pinned official package; no runtime CDN or full bundle.
const require = createRequire(new URL('../../../packages/site/chrome/package.json', import.meta.url));
const dependency = dirname(require.resolve('lucide-static/package.json'));
const metadata = JSON.parse(await readFile(resolve(dependency, 'package.json'), 'utf8'));
assert.equal(metadata.version, '1.66.0', 'Review icon changes before upgrading the pinned source');
const names = {
  grid: 'layout-grid', energy: 'zap', route: 'route', factory: 'factory',
  water: 'droplet', buildings: 'building-2', warehouse: 'warehouse',
  cube: 'box', link: 'handshake', external: 'external-link',
  left: 'chevron-left', right: 'chevron-right', down: 'arrow-down',
};
const icons = {};
for (const [key, name] of Object.entries(names)) {
  const source = await readFile(resolve(dependency, 'icons', `${name}.svg`), 'utf8');
  // Only normalize presentation attributes; official geometry stays intact.
  icons[key] = source.replace(/<!--[\s\S]*?-->/g, '').trim()
    .replace('<svg', '<svg aria-hidden="true" focusable="false"')
    .replace(/\bclass="/, 'class="ui-icon ')
    .replace(/\bwidth="24"/, 'width="18"').replace(/\bheight="24"/, 'height="18"')
    .replace(/\bstroke-width="2"/, 'stroke-width="1.5"').replace(/\s+/g, ' ');
}
const generated = '// Generated by scripts/generate-icons.mjs from lucide-static 1.66.0. Do not edit.\n'
  + '// Geometry: official Lucide icons; license: ./LUCIDE-LICENSE (ISC / inherited MIT).\n'
  + `export const icons = Object.freeze(${JSON.stringify(icons, null, 2)});\n`;
const license = await readFile(resolve(dependency, 'LICENSE'), 'utf8');
const htmlPath = resolve(root, 'index.html');
const original = await readFile(htmlPath, 'utf8');
let count = 0;
const html = original.replace(/(<span class="icon-holder" data-showcase-icon="([a-z]+)">)[\s\S]*?(<\/span>)/g, (_, open, key, close) => {
  assert(Object.hasOwn(icons, key), `Unknown static icon: ${key}`);
  count++;
  return open + icons[key] + close;
});
assert.equal(count, 3, 'Expected two header icons and one browse arrow');
for (const [path, contents] of [['runtime/icons.generated.mjs', generated], ['runtime/LUCIDE-LICENSE', license], ['index.html', html]]) {
  if (process.argv.includes('--check')) assert.equal(await readFile(resolve(root, path), 'utf8'), contents, `Stale Lucide asset: ${path}`);
  else await writeFile(resolve(root, path), contents);
}
console.log(`Enterprise Lucide icons ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${Object.keys(icons).length} fixed icons and 3 static placements.`);
